//Declaring a variable

let message;
message = "Hello World!";
console.log(message);

//Declaring and assigning a variable in one statement

let message2 = "Hello World!";
console.log(message2);

//Declaring multiple variables in one statement

let name = "John", age = 30, city = "New York";
console.log(name);
console.log(age);
console.log(city);

//Declaring a variable without assigning a value

let myVariable;
console.log(myVariable); // Output: undefined

//Declaring a variable with a value of null
let myNullVariable = null;
console.log(myNullVariable); // Output: null

//Declaring a variable in multiple lines

let firstName = "John",
    lastName = "Doe",
    age2 = 30;
console.log(firstName);
console.log(lastName);
console.log(age2);


